// 這裡的字串刻意與 ZoneStatusList.vue 的狀態標籤一致，不另創說法。
const contextLabel = computed(() => {
  switch (props.tone) {
    case "tracking":
      return "提醒進行中";
    case "soon":
      return "快到補擦時間";
    case "due":
      return "建議現在補擦";
    case null:
      return "本機提醒";
  }
});
</script>

